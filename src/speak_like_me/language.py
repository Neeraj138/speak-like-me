def _collapsed(token: str) -> str:
    """Collapse emphatic typing such as ``entiii`` while retaining double letters."""
    return re.sub(r"(.)\1{2,}", r"\1", token)


def contains_telugu_or_mixed(text: str) -> bool:
    if TELUGU_SCRIPT_RE.search(text):
        return True
    raw_tokens = [token.casefold() for token in LATIN_TOKEN_RE.findall(text)]
    tokens = raw_tokens + [_collapsed(token) for token in raw_tokens]
    if any(token in STRONG_TELUGU_TOKENS for token in tokens):
        return True
    # Repeated weak words count once; this avoids classifying an English message with
    # repeated fillers such as "aa" as Telugu.
    weak_hits = len(set(tokens) & WEAK_TELUGU_TOKENS)
    return weak_hits >= 2
